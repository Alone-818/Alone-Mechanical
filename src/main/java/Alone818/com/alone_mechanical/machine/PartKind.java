package Alone818.com.alone_mechanical.machine;
public enum PartKind {
    CASING, REINFORCED, ENERGY_COIL, EFFICIENCY_COIL, GLASS, ITEM_PORT, FLUID_PORT, GAS_PORT, CONTROLLER, FLUID_TANK, GAS_TANK, ITEM_VAULT, ENERGY_MATRIX, PROCESSING_MATRIX, STORAGE_TANK, UNIVERSAL_PORT,
    FORGING_COMPONENT, CALCINATION_COMPONENT, ALLOY_COMPONENT, COMPOUND_COMPONENT, DECOMPOSITION_COMPONENT, FORMING_COMPONENT, INFUSION_COMPONENT, SLAUGHTER_FIELD_COMPONENT, BREEDING_FIELD_COMPONENT, HARVEST_FIELD_COMPONENT, REPELLER_FIELD_COMPONENT, TURBINE_ROTOR, REACTOR_FUEL_ROD,
    CRUSHING_COMPONENT, BOILER_COMPONENT, TURBINE_COMPONENT, CONVERSION_COMPONENT,
    DISTILLATION_COMPONENT, CONDENSATION_COMPONENT, EXCHANGE_COMPONENT, AIR_SEPARATION_COMPONENT, SYNTHESIS_COMPONENT;
    public boolean isComponent(){return name().endsWith("_COMPONENT");}
    public boolean isPort() { return this == ITEM_PORT || this == FLUID_PORT || this == GAS_PORT || this == UNIVERSAL_PORT; }
    public boolean isTank() { return this == FLUID_TANK || this == GAS_TANK || this == STORAGE_TANK; }
    public boolean isStorage() { return isTank() || this == ITEM_VAULT; }
}
